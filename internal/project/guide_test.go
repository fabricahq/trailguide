// Verify guide upgrades preserve authored files and refuse ambiguous ownership.

package project

import (
	"bytes"
	"context"
	"crypto/sha256"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"testing"
)

// TestProjectGuideRefresh updates an older generated guide while preserving configuration and local guidance byte for byte.
func TestProjectGuideRefresh(t *testing.T) {
	ctx := context.Background()
	directory := filepath.Join(t.TempDir(), ".trailguide")
	options := Options{Directory: filepath.Dir(directory)}
	if _, err := Initialize(ctx, options); err != nil {
		t.Fatal(err)
	}
	old := stampProjectGuide([]byte("# Earlier release guide\n"))
	config := []byte("{\n  \"schemaVersion\": 2, \"sources\": {}\n}\n")
	local := []byte("My local authoring notes.\n")
	for name, data := range map[string][]byte{"README.md": old, "config.yaml": config, "rules/README.md": local} {
		if err := os.WriteFile(filepath.Join(directory, name), data, 0600); err != nil {
			t.Fatal(err)
		}
	}
	result, err := Initialize(ctx, options)
	if err != nil || len(result.Written()) != 1 || result.Written()[0] != filepath.Join(directory, "README.md") {
		t.Fatal(result, err)
	}
	for name, want := range map[string][]byte{"README.md": renderProjectGuide(), "config.yaml": config, "rules/README.md": local} {
		got, err := os.ReadFile(filepath.Join(directory, name))
		if err != nil || !bytes.Equal(got, want) {
			t.Fatal(name, err)
		}
	}
	if result, err := Initialize(ctx, options); err != nil || len(result.Written()) != 0 {
		t.Fatal(result, err)
	}
}

// TestProjectGuideRefreshesTheCodeRulesGuide of a project that still keeps its files in .code-rules/, refreshing,
// in that directory, an unedited guide that Code Rules stamped before the rename.
func TestProjectGuideRefreshesTheCodeRulesGuide(t *testing.T) {
	ctx := context.Background()
	root := t.TempDir()
	options := Options{Directory: root}
	if _, err := Initialize(ctx, options); err != nil {
		t.Fatal(err)
	}
	directory := filepath.Join(root, ".code-rules")
	if err := os.Rename(filepath.Join(root, ".trailguide"), directory); err != nil {
		t.Fatal(err)
	}
	body := []byte("> **Generated by Code Rules. Do not edit this file manually.**\n# Earlier release guide\n")
	old := append([]byte(fmt.Sprintf("<!-- code-rules:project-guide sha256:%x -->\n", sha256.Sum256(body))), body...)
	if err := os.WriteFile(filepath.Join(directory, "README.md"), old, 0600); err != nil {
		t.Fatal(err)
	}
	result, err := Initialize(ctx, options)
	// The AGENTS.md section init wrote for .trailguide/ now points to .code-rules/.
	if err != nil || !slices.Equal(result.Written(), []string{filepath.Join(directory, "README.md"), filepath.Join(root, "AGENTS.md")}) {
		t.Fatal(result, err)
	}
	if got, err := os.ReadFile(filepath.Join(root, "AGENTS.md")); err != nil || !bytes.Contains(got, []byte("Read `.code-rules/_managed/generated/RULES.md`")) {
		t.Fatal(string(got), err)
	}
	if got, err := os.ReadFile(filepath.Join(directory, "README.md")); err != nil || !bytes.Equal(got, renderProjectGuide()) {
		t.Fatal(err)
	}
	if _, err := os.Lstat(filepath.Join(root, ".trailguide")); !os.IsNotExist(err) {
		t.Fatalf("init created .trailguide/ beside .code-rules/: %v", err)
	}
}

// TestProjectGuideRefusesUnmanagedFilesAndLinks verifies collisions fail before scaffolding is published.
func TestProjectGuideRefusesUnmanagedFilesAndLinks(t *testing.T) {
	for _, kind := range []string{"authored", "edited", "symlink"} {
		t.Run(kind, func(t *testing.T) {
			directory := filepath.Join(t.TempDir(), ".trailguide")
			if err := os.Mkdir(directory, 0700); err != nil {
				t.Fatal(err)
			}
			guide := filepath.Join(directory, "README.md")
			content := []byte("# My project notes\n")
			if kind == "edited" {
				content = append(stampProjectGuide([]byte("Old guide\n")), []byte("Edit\n")...)
			}
			if kind == "symlink" {
				target := filepath.Join(t.TempDir(), "notes.md")
				if err := os.WriteFile(target, content, 0600); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink(target, guide); err != nil {
					t.Fatal(err)
				}
			} else if err := os.WriteFile(guide, content, 0600); err != nil {
				t.Fatal(err)
			}
			if _, err := Initialize(context.Background(), Options{Directory: filepath.Dir(directory)}); err == nil {
				t.Fatal("expected refusal")
			}
			got, err := os.ReadFile(guide)
			if err != nil || !bytes.Equal(got, content) {
				t.Fatal("overwrote guide", err)
			}
			entries, err := os.ReadDir(directory)
			if err != nil || len(entries) != 1 {
				t.Fatal("published partial scaffolding", entries, err)
			}
		})
	}
}

// TestProjectGuideDefault agrees with the project operations' omitted configuration path.
func TestProjectGuideDefault(t *testing.T) {
	name, content := projectGuide()
	_, body, _ := bytes.Cut(content, []byte("\n"))
	if !bytes.HasPrefix(body, []byte("> **Generated by Trail Guide. Do not edit this file manually.**\n")) || !bytes.Contains(body, []byte("trailguide project build")) {
		t.Fatal("missing managed guide notice", string(content))
	}
	if name != "README.md" || !bytes.Equal(content, renderProjectGuide()) {
		t.Fatal("default guide must match .trailguide/config.yaml", name)
	}
}
