// TestPrepareRetainsTermsWithoutActiveRules copies binary terms unchanged even after every upstream rule is excluded.
func TestPrepareRetainsTermsWithoutActiveRules(t *testing.T) {
	config, libraries := fixture(t, `[{"id":"techs/go/errors","reason":"Use local policy"}]`)
	supplied := libraries["team"]
	terms := []byte{'x', '\r', '\n', 0, 255}
	supplied.Catalog.License = &trailguide.LicenseDeclaration{Files: []string{"LICENSE"}, AttributionFiles: []string{"NOTICE"}}
	supplied.Catalog.SupportingFiles["LICENSE"] = terms
	supplied.Catalog.SupportingFiles["NOTICE"] = []byte("Notice\r\n")
	libraries["team"] = supplied
	resolved, err := resolve(config, libraries, nil)
	if err != nil {
		t.Fatal(err)
	}
	options := Options{IndexMaxLines: defaultIndexMaxLines}
	got, err := prepare(resolved, options)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(got.Files["libraries/team/README.md"]), "> **Generated by Trail Guide.") || !strings.Contains(string(got.Files["libraries/team/README.md"]), "Do not edit these copies") {
		t.Fatal("missing copied-terms notice")
	}
	file := "libraries/team/licenses/LICENSE.md"
	if !bytes.Equal(got.Files[file], terms) || string(got.Files["libraries/team/licenses/notices/001.md"]) != "Notice\r\n" {
		t.Fatal("changed terms")
	}
	if _, ok := got.Files["rules/team/techs/go/errors.md"]; ok {
		t.Fatal("rendered excluded rule")
	}
	again, err := prepare(resolved, options)
	if err != nil || !reflect.DeepEqual(got, again) {
		t.Fatal("nondeterministic output")
	}
	got.Files[file][0] = 'z'
	if terms[0] != 'x' {
		t.Fatal("output aliases original term bytes")
	}
}

// TestPrepareNamesTheReplacedRule puts the library rule a replacement replaces, its basis, and the reason on the
// replacement's page, which declares no library license, points rules/README.md to the lockfile, and writes no
// provenance file.
func TestPrepareNamesTheReplacedRule(t *testing.T) {
	config, libraries := fixture(t, `[{"id":"techs/go/errors","reason":"Project policy","replacedBy":"techs/go/custom","basedOn":"1.0.0"}]`)
	lib := libraries["team"]
	lib.Catalog.License = &trailguide.LicenseDeclaration{Files: []string{"LICENSE"}}
	lib.Catalog.SupportingFiles["LICENSE"] = []byte("Terms")
	libraries["team"] = lib
	resolved, err := resolve(config, libraries, map[string][]byte{"techs/go/custom.md": []byte(document)})
	if err != nil {
		t.Fatal(err)
	}
	got, err := prepare(resolved, Options{IndexMaxLines: defaultIndexMaxLines})
	if err != nil {
		t.Fatal(err)
	}
	page := string(got.Files["rules/local/techs/go/custom.md"])
	if !strings.Contains(page, "Rule ID: `local:techs/go/custom`\n\nReplaces: `team:techs/go/errors`, based on version 1.0.0.\n\nReason: Project policy\n\n**When to read:**") {
		t.Errorf("replacement page:\n%s", page)
	}
	if strings.Contains(page, "Declared license") || strings.Contains(page, "licenses/") {
		t.Errorf("the replacement inherited the library's license:\n%s", page)
	}
	if readme := string(got.Files["rules/README.md"]); !strings.Contains(readme, "[lock.json](../../../lock.json)") {
		t.Errorf("rules/README.md doesn't point to the lockfile:\n%s", readme)
	}
	if _, written := got.Files["provenance.json"]; written {
		t.Error("wrote provenance.json")
	}
}

// TestPrepareNoPartialOutput rejects missing term bytes and invalid budgets after resolution.
func TestPrepareNoPartialOutput(t *testing.T) {
	config, libraries := fixture(t, `[]`)
	resolved, err := resolve(config, libraries, nil)
	if err != nil {
		t.Fatal(err)
	}
	if output, err := prepare(resolved, Options{IndexMaxLines: 0}); err == nil || output.Files != nil {
		t.Fatal("accepted invalid options or returned partial output")
	}
	resolved.Sources[0].License = &trailguide.LicenseDeclaration{Files: []string{"missing"}}
	output, err := prepare(resolved, Options{IndexMaxLines: defaultIndexMaxLines})
	if err == nil || output.Files != nil {
		t.Fatal("accepted missing terms")
	}
}

// TestPrepareKeepsGuidanceInput renders a group with library and local guidance without changing the resolved input.
func TestPrepareKeepsGuidanceInput(t *testing.T) {
	config, libraries := fixture(t, `[]`)
	resolved, err := resolve(config, libraries, map[string][]byte{"techs/go/_group.yaml": []byte(`{"name":"Local Go","description":"Local policy","whenToRead":"When editing Go"}`)})
	if err != nil {
		t.Fatal(err)
	}
	original := append([]groupGuidance(nil), resolved.Groups[0].Guidance...)
	if _, err := prepare(resolved, Options{IndexMaxLines: defaultIndexMaxLines}); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(resolved.Groups[0].Guidance, original) {
		t.Fatal("mutated input guidance")
	}
}

// generateWith resolves and renders the fixture after alter changes its source's snapshot, with group pages
// limited to summaries.
func generateWith(t *testing.T, alter func(*library.Snapshot, *rules.Source)) map[string]string {
	t.Helper()
	config, libraries := fixture(t, `[]`)
	team := libraries["team"]
	alter(&team.Snapshot, &config.Sources[0])
	libraries["team"] = team
	resolved, err := resolve(config, libraries, nil)
	if err != nil {
		t.Fatal(err)
	}
	summaries := 0
	output, err := prepare(resolved, Options{IndexMaxLines: defaultIndexMaxLines, GroupInlineMaxBytes: &summaries})
	if err != nil {
		t.Fatal(err)
	}
	files := map[string]string{}
	for name, data := range output.Files {
		files[name] = string(data)
	}
	return files
}

// TestPrepareLinksToARuleWhereItsCommitKeepsIt links an imported rule's source to its file in .trailguide/rules/,
// or at the repository root when the commit that published it keeps the layout before version 2.
func TestPrepareLinksToARuleWhereItsCommitKeepsIt(t *testing.T) {
	older := strings.Repeat("b", 40)
	for legacy, path := range map[bool]string{false: ".trailguide/rules/techs/go/errors.md", true: "techs/go/errors.md"} {
		files := generateWith(t, func(snapshot *library.Snapshot, source *rules.Source) {
			version := trailguide.RuleVersion{Major: 1, Minor: 3}
			snapshot.Release = 2
			snapshot.Rules["techs/go/errors"] = library.ImportedRule{Version: &version, Release: 1, Commit: older, LegacyLayout: legacy}
			source.Ref = rules.GitRef{}
		})
		if want := "(https://github.com/acme/rules/blob/" + older + "/" + path + ")"; !strings.Contains(files["rules/team/techs/go/errors.md"], want) {
			t.Errorf("legacy layout %t: the source link isn't %s:\n%s", legacy, want, files["rules/team/techs/go/errors.md"])
		}
	}
}

// TestPrepareShowsEachImportedRulesVersion puts the version below the rule ID in guidance, and links the rule's
// source at the rule's own commit.
func TestPrepareShowsEachImportedRulesVersion(t *testing.T) {
	older := strings.Repeat("b", 40)
	files := generateWith(t, func(snapshot *library.Snapshot, source *rules.Source) {
		version := trailguide.RuleVersion{Major: 1, Minor: 3}
		snapshot.Release = 2
		snapshot.Rules["techs/go/errors"] = library.ImportedRule{Version: &version, Release: 1, Commit: older}
		source.Ref = rules.GitRef{}
		source.Pins = map[string]rules.Pin{"techs/go/errors": {Version: version, Reason: "Waiting on | review."}}
	})
	for _, name := range []string{"rules/team/techs/go/errors.md", "groups/techs/go.md"} {
		if !strings.Contains(files[name], "Rule ID: `team:techs/go/errors`\n\nVersion: 1.3.0\n\n**When to read:**") {
			t.Errorf("%s doesn't show the version below the rule ID:\n%s", name, files[name])
		}
	}
	if !strings.Contains(files["rules/team/techs/go/errors.md"], "https://github.com/acme/rules/blob/"+older+"/.trailguide/rules/techs/go/errors.md") {
		t.Error("the source link doesn't use the rule's own commit")
	}
}

