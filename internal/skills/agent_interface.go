// Render the file Codex reads a skill's display name, short description, and default prompt from, using the
// agent-neutral metadata keys in SKILL.md.

package skills

import (
	"bytes"
	"strings"

	"go.yaml.in/yaml/v4"
)

// The metadata keys that give agents' interfaces the text to show for a skill. They name no agent, so other agents
// with interface metadata can map the same values.
const (
	DisplayNameKey      = "display-name"
	ShortDescriptionKey = "short-description"
	DefaultPromptKey    = "default-prompt"
)

// OpenAIFile is the path, in an installed skill folder, of the file Codex reads a skill's interface text from.
const OpenAIFile = "agents/openai.yaml"

// Interface is the text a skill's metadata gives agents' interfaces to show. A field is empty when the skill doesn't
// declare it; ReadMetadata keeps each one as written, and OpenAIInterface trims surrounding whitespace.
type Interface struct {
	DisplayName, ShortDescription, DefaultPrompt string
}

// IsZero reports whether the skill declares no interface text: every field is empty or blank.
func (i Interface) IsZero() bool {
	return strings.TrimSpace(i.DisplayName) == "" && strings.TrimSpace(i.ShortDescription) == "" && strings.TrimSpace(i.DefaultPrompt) == ""
}

// OpenAIInterface returns the contents of OpenAIFile for a skill installed as name whose metadata declares i: a
// generated-file comment, then interface.display_name, short_description, and default_prompt, each double-quoted.
// The display name falls back to name, and the other two are left out when the skill doesn't declare them. It
// returns nil when i is zero, so a skill that declares none of the fields gets no file.
func OpenAIInterface(i Interface, name string) []byte {
	if i.IsZero() {
		return nil
	}
	display := strings.TrimSpace(i.DisplayName)
	if display == "" {
		display = name
	}
	fields := []*yaml.Node{}
	for _, field := range [][2]string{{"display_name", display}, {"short_description", strings.TrimSpace(i.ShortDescription)}, {"default_prompt", strings.TrimSpace(i.DefaultPrompt)}} {
		if field[1] == "" {
			continue
		}
		fields = append(fields, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: field[0]}, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: field[1], Style: yaml.DoubleQuotedStyle})
	}
	document := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map", Content: []*yaml.Node{
		{Kind: yaml.ScalarNode, Tag: "!!str", Value: "interface"},
		{Kind: yaml.MappingNode, Tag: "!!map", Content: fields},
	}}
	var out bytes.Buffer
	out.WriteString("# Generated by Trail Guide from the " + DisplayNameKey + ", " + ShortDescriptionKey + ", and " + DefaultPromptKey + " metadata in SKILL.md. Do not edit.\n")
	encoder := yaml.NewEncoder(&out)
	encoder.SetIndent(2)
	if err := encoder.Encode(document); err != nil {
		// A mapping of plain string scalars always encodes.
		panic(err)
	}
	if err := encoder.Close(); err != nil {
		panic(err)
	}
	return out.Bytes()
}
