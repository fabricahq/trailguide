// Test the Codex interface file rendered from a skill's interface metadata.

package skills_test

import (
	"testing"

	"github.com/fabricahq/trailguide/internal/skills"
)

func TestOpenAIInterfaceRendersTheDeclaredFields(t *testing.T) {
	header := "# Generated by Trail Guide from the display-name, short-description, and default-prompt metadata in SKILL.md. Do not edit.\n"
	tests := map[string]struct {
		metadata skills.Interface
		want     string
	}{
		"every field": {
			skills.Interface{DisplayName: "Add Skill", ShortDescription: "Create and place Fabrica agent skills", DefaultPrompt: "Use $add-skill to create or update a Fabrica agent skill."},
			header + "interface:\n  display_name: \"Add Skill\"\n  short_description: \"Create and place Fabrica agent skills\"\n  default_prompt: \"Use $add-skill to create or update a Fabrica agent skill.\"\n",
		},
		"display name falls back to the install name": {
			skills.Interface{ShortDescription: "  Create skills\n"},
			header + "interface:\n  display_name: \"add-skill\"\n  short_description: \"Create skills\"\n",
		},
		"only a display name": {
			skills.Interface{DisplayName: "Add Skill", DefaultPrompt: " "},
			header + "interface:\n  display_name: \"Add Skill\"\n",
		},
		"quotes and line breaks are escaped": {
			skills.Interface{DisplayName: `Say "hi"`, DefaultPrompt: "First line.\nSecond: line."},
			header + "interface:\n  display_name: \"Say \\\"hi\\\"\"\n  default_prompt: \"First line.\\nSecond: line.\"\n",
		},
	}
	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			if got := string(skills.OpenAIInterface(test.metadata, "add-skill")); got != test.want {
				t.Fatalf("OpenAIInterface =\n%s\nwant\n%s", got, test.want)
			}
		})
	}
}

func TestOpenAIInterfaceReturnsNilWithoutInterfaceText(t *testing.T) {
	for _, metadata := range []skills.Interface{{}, {DisplayName: " ", ShortDescription: "\n", DefaultPrompt: "\t"}} {
		if got := skills.OpenAIInterface(metadata, "add-skill"); got != nil {
			t.Errorf("OpenAIInterface(%#v) = %q, want nil", metadata, got)
		}
	}
}
